import { test, expect } from '@playwright/test';

test('create project, upload cover, discuss, moderate, assign access and archive without losing comments', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const login = async (username: string, password: string) => {
    await page.goto('/');
    await page.getByLabel('Имя пользователя', { exact: true }).fill(username);
    await page.getByLabel('Пароль', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Войти', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Библиотека', exact: true })).toBeVisible();
  };
  await login('editor', 'browser-test-editor-password');
  await page.getByRole('link', { name: '+ Добавить игру', exact: true }).click();
  await page.getByLabel('Название игры').fill('Orbit Lab');
  await page.getByLabel('Короткий адрес страницы').fill('orbit-lab');
  await page.getByLabel('Описание', { exact: true }).fill('Небольшой орбитальный эксперимент.\nПроверяем управление и собираем обратную связь команды.');
  await page.getByRole('button', { name: 'Создать карточку', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Orbit Lab', exact: true })).toBeVisible();
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 1200; canvas.height = 675;
    const context = canvas.getContext('2d')!;
    const gradient = context.createLinearGradient(0, 0, 1200, 675); gradient.addColorStop(0, '#0c274d'); gradient.addColorStop(1, '#165e75');
    context.fillStyle = gradient; context.fillRect(0, 0, 1200, 675);
    context.strokeStyle = '#53d1ee'; context.lineWidth = 4;
    context.beginPath(); context.ellipse(600, 330, 380, 160, -.45, 0, Math.PI * 2); context.stroke();
    context.fillStyle = '#c3f5ff'; context.beginPath(); context.arc(600, 330, 80, 0, Math.PI * 2); context.fill();
    context.fillStyle = '#fff'; context.font = 'bold 68px sans-serif'; context.fillText('ORBIT LAB', 60, 590);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.getByLabel('Файл обложки').setInputFiles({ name: 'orbit.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.getByRole('button', { name: 'Загрузить обложку' }).click();
  await expect(page.getByRole('status')).toHaveText('Обложка обновлена.');
  await expect(page.locator('.cover-editor img')).toBeVisible();
  await page.getByRole('link', { name: 'Открыть страницу игры →' }).click();
  await expect(page.getByRole('heading', { name: 'Orbit Lab', exact: true })).toBeVisible();
  await page.getByLabel('Ваш комментарий').fill('<img src=x onerror="window.untrusted=true"> Проверить управление');
  await page.getByRole('button', { name: 'Отправить комментарий' }).click();
  await expect(page.locator('.comment-body')).toHaveText('<img src=x onerror="window.untrusted=true"> Проверить управление');
  expect(await page.evaluate(() => 'untrusted' in window)).toBe(false);
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await page.getByLabel('Текст комментария').fill('Управление проверено. Нужен более плавный поворот.');
  await page.getByRole('button', { name: 'Сохранить комментарий' }).click();
  await expect(page.locator('.comment-body')).toHaveText('Управление проверено. Нужен более плавный поворот.');
  await page.getByRole('button', { name: 'Скрыть', exact: true }).click();
  await expect(page.locator('.comment')).toHaveCount(0);
  await page.getByLabel('Показать скрытые').check();
  await expect(page.locator('.comment-hidden')).toHaveCount(1);
  await page.getByRole('button', { name: 'Восстановить', exact: true }).click();
  await expect(page.locator('.comment-hidden')).toHaveCount(0);
  await expect(page.locator('.comment')).toHaveCount(1);
  await page.screenshot({ path: 'test-results/project-desktop.png', fullPage: true });

  await page.getByRole('link', { name: 'Команда', exact: true }).click();
  await page.getByRole('button', { name: 'Тестер проекта Тестер', exact: true }).click();
  await page.getByLabel('Orbit Lab', { exact: true }).check();
  await page.getByRole('button', { name: 'Сохранить изменения' }).click();
  await expect(page.getByRole('status')).toHaveText('Изменения сохранены.');
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await login('project-tester', 'browser-test-tester-password');
  await page.getByRole('link', { name: /Orbit Lab/ }).click();
  await page.getByLabel('Ваш комментарий').fill('Проверено на телефоне: касания работают.');
  await page.getByRole('button', { name: 'Отправить комментарий' }).click();
  await expect(page.locator('.comment')).toHaveCount(2);
  await expect(page.getByRole('button', { name: 'Скрыть', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Редактировать', exact: true })).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/project-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(page.locator('.comment')).toHaveCount(2);
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await login('editor', 'browser-test-editor-password');
  await page.getByRole('link', { name: /Orbit Lab/ }).click();
  await page.getByRole('link', { name: 'Редактировать игру', exact: true }).click();
  await page.getByRole('button', { name: 'В архив', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Игра перенесена в архив.');
  await page.getByRole('link', { name: 'Открыть страницу игры →' }).click();
  await expect(page.getByText('Игра в архиве. Обсуждение доступно только для чтения.')).toBeVisible();
  await expect(page.locator('.comment')).toHaveCount(2);
  await page.getByRole('link', { name: 'Редактировать игру', exact: true }).click();
  await page.getByRole('button', { name: 'Вернуть из архива' }).click();
  await expect(page.getByRole('status')).toHaveText('Игра возвращена в библиотеку.');
  await page.getByRole('link', { name: 'Библиотека', exact: true }).click();
  await expect(page.getByRole('link', { name: /Orbit Lab/ })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/library-desktop.png', fullPage: true });
  expect(errors).toEqual([]);
});
