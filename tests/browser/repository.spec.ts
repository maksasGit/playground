import { test, expect } from '@playwright/test';

test('public repository connection, main check, persistence and disconnect without GitHub credentials', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Имя пользователя', { exact: true }).fill('editor');
  await page.getByLabel('Пароль', { exact: true }).fill('browser-test-editor-password');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByRole('link', { name: '+ Добавить игру', exact: true }).click();
  await page.getByLabel('Название игры').fill('Public repository test');
  await page.getByLabel('Короткий адрес страницы').fill('public-repository');
  await page.getByRole('button', { name: 'Создать карточку', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Исходники на GitHub' });
  await expect(panel.getByText('Ветка: main')).toBeVisible();
  await panel.getByLabel('Ссылка на GitHub').fill('https://example.com/team/game');
  await panel.getByRole('button', { name: 'Подключить репозиторий' }).click();
  await expect(panel.getByRole('alert')).toContainText('https://github.com/owner/repository');
  await panel.getByLabel('Ссылка на GitHub').fill('https://github.com/test-team/public-game.git');
  await panel.getByRole('button', { name: 'Подключить репозиторий' }).click();
  await expect(panel.getByRole('status')).toHaveText('Репозиторий подключён. Ветка main проверена.');
  await expect(panel.getByLabel('Ссылка на GitHub')).toHaveValue('https://github.com/test-team/public-game');
  await expect(panel.getByText('Версия найдена · ещё не опубликована')).toBeVisible();
  await expect(panel.getByRole('link', { name: 'aaaaaaaaaaaa ↗' })).toBeVisible();
  await page.reload();
  await expect(panel.getByRole('link', { name: 'aaaaaaaaaaaa ↗' })).toBeVisible();
  await panel.getByRole('button', { name: 'Проверить обновления' }).click();
  await expect(panel.getByRole('link', { name: 'bbbbbbbbbbbb ↗' })).toBeVisible();
  await expect(panel.getByText('Updated public main', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/repository-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/repository-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await panel.getByRole('button', { name: 'Отключить репозиторий' }).click();
  await expect(panel.getByLabel('Ссылка на GitHub')).toHaveValue('');
  await expect(panel.getByRole('button', { name: 'Проверить обновления' })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Public repository test', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
