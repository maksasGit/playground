import { test, expect } from '@playwright/test';

test('team workflow: first login, create colleague, permissions, mobile, logout and session restore', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Войти в Playground' })).toBeVisible();
  await page.screenshot({ path: 'test-results/login-desktop.png', fullPage: true });
  await page.getByLabel('Имя пользователя', { exact: true }).fill('owner');
  await page.getByLabel('Пароль', { exact: true }).fill('browser-test-initial-password');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Задайте свой пароль' })).toBeVisible();
  await expect(page.getByRole('navigation')).toHaveCount(0);
  await page.getByLabel('Текущий пароль', { exact: true }).fill('browser-test-initial-password');
  await page.getByLabel('Новый пароль', { exact: true }).fill('browser-test-owner-password');
  await page.getByLabel('Повторите новый пароль').fill('browser-test-owner-password');
  await page.getByRole('button', { name: 'Сохранить пароль' }).click();
  await expect(page.getByRole('heading', { name: 'Библиотека', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: /Первая игра/ })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Библиотека', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Команда', exact: true }).click();
  await page.getByRole('button', { name: '+ Создать аккаунт' }).click();
  await page.getByLabel('Имя пользователя', { exact: true }).fill('colleague');
  await page.getByLabel('Отображаемое имя').fill('Коллега');
  await page.getByLabel('Начальный пароль', { exact: true }).fill('browser-test-colleague-password');
  await page.getByLabel('Роль', { exact: true }).selectOption('Viewer');
  await page.getByLabel('Первая игра', { exact: true }).check();
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'colleague', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/team-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await page.getByLabel('Имя пользователя', { exact: true }).fill('colleague');
  await page.getByLabel('Пароль', { exact: true }).fill('browser-test-colleague-password');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Задайте свой пароль' })).toBeVisible();
  await page.getByLabel('Текущий пароль', { exact: true }).fill('browser-test-colleague-password');
  await page.getByLabel('Новый пароль', { exact: true }).fill('browser-test-colleague-changed');
  await page.getByLabel('Повторите новый пароль').fill('browser-test-colleague-changed');
  await page.getByRole('button', { name: 'Сохранить пароль' }).click();
  await expect(page.getByRole('link', { name: /Первая игра/ })).toBeVisible();
  await expect(page.getByRole('link', { name: /Вторая игра/ })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Команда', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: /Первая игра/ }).click();
  await expect(page.getByRole('heading', { name: 'Первая игра', exact: true })).toBeVisible();
  await expect(page.getByText(/У вас доступ на чтение/)).toBeVisible();
  expect(await page.evaluate(() => 'untrusted' in window)).toBe(false);
  await page.screenshot({ path: 'test-results/game-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto('/#/admin/users');
  await expect(page.getByRole('heading', { name: 'Страница недоступна' })).toBeVisible();
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Войти в Playground' })).toBeVisible();
  expect(errors).toEqual([]);
});
